"""Run the compiled dbt analyses (the SQL of the five business questions) and save the results.

`make dbt-results` first runs `dbt compile --select path:analyses`; this script executes every
compiled query against the persistent DuckDB file (read-only) and writes

    dbt/reports/<query>.sql   the exact SQL that was executed
    dbt/reports/<query>.csv   the result table
    dbt/reports/results.md    all questions with their SQL-free result tables
"""

import argparse
import csv
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

import duckdb

TITLES = {
    "q1": "Q1 - Active enrollments per training",
    "q2": "Q2 - Completion and abandonment by training and funding type",
    "q3": "Q3 - Curriculum progress versus elapsed time (behind schedule = gap <= -0.15)",
    "q4": "Q4 - NPS per training and quarter",
    "q5": "Q5 - Coach utilization",
}


def render(value) -> str:
    if value is None:
        return ""
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, float):
        return f"{value:.4f}".rstrip("0").rstrip(".")
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    return str(value)


def markdown_table(columns, rows) -> str:
    lines = [
        "| " + " | ".join(columns) + " |",
        "|" + "|".join("---" for _ in columns) + "|",
    ]
    for row in rows:
        lines.append(
            "| " + " | ".join(render(value).replace("|", "/") for value in row) + " |"
        )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--database", required=True)
    parser.add_argument(
        "--compiled-dir", default="dbt/target/compiled/stackfuel/analyses"
    )
    parser.add_argument("--output-dir", default="dbt/reports")
    args = parser.parse_args()

    compiled = sorted(Path(args.compiled_dir).glob("*.sql"))
    if not compiled:
        raise SystemExit(
            f"No compiled analyses in {args.compiled_dir}; run `dbt compile` first"
        )
    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    connection = duckdb.connect(args.database, read_only=True)
    connection.execute("SET TimeZone = 'UTC'")

    sections = [
        "# Results of the five business questions\n",
        "Reporting date (Stichtag): 2026-08-31. Generated by `make dbt-results` from the `reporting` "
        "models; the executed SQL of every question is next to its CSV file (`dbt/analyses/*.sql` "
        "with `ref()` resolved).\n",
    ]
    for path in compiled:
        sql = path.read_text(encoding="utf-8")
        cursor = connection.execute(sql)
        columns = [description[0] for description in cursor.description]
        rows = cursor.fetchall()
        (output / path.name).write_text(sql, encoding="utf-8")
        with (output / f"{path.stem}.csv").open(
            "w", newline="", encoding="utf-8"
        ) as handle:
            writer = csv.writer(handle)
            writer.writerow(columns)
            writer.writerows([[render(value) for value in row] for row in rows])
        title = TITLES.get(path.stem.split("_")[0], path.stem)
        sections.append(
            f"\n## {title}\n\nSQL: `dbt/reports/{path.name}` ({len(rows)} rows)\n"
        )
        sections.append(markdown_table(columns, rows) + "\n")
        print(f"{path.stem}: {len(rows)} rows")
    (output / "results.md").write_text("\n".join(sections), encoding="utf-8")
    connection.close()


if __name__ == "__main__":
    main()
